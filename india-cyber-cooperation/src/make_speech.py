"""Generate speech_mn.js / speech_en.js (speaker notes per slide) from the Markdown scripts."""
import re, json, sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
def parse(path, tag):
    t = open(path, encoding="utf-8").read()
    sections, cur, buf = {}, None, []
    for ln in t.split("\n"):
        m = re.match(r'^### \[%s (\d+)\]\s*(.*)$' % tag, ln)
        if m:
            if cur: sections[cur] = buf
            cur = int(m.group(1)); buf = ["%s %s · %s" % (tag, cur, m.group(2).strip())]; continue
        if cur and (ln.startswith("### ") or ln.startswith("## ") or ln.strip() == "---"):
            sections[cur] = buf; cur = None; continue
        if cur: buf.append(ln)
    if cur: sections[cur] = buf
    out = {}
    for k, v in sections.items():
        txt = "\n".join(v).strip()
        txt = re.sub(r'\*([^*]+)\*', r'[\1]', txt)
        out[str(k)] = re.sub(r'\n{3,}', '\n\n', txt)
    return out
for src, tag, dst in [("../iltgegchiin_yaria_mn.md", "Слайд", "speech_mn.js"), ("../iltgegchiin_yaria_en.md", "Slide", "speech_en.js")]:
    d = parse(os.path.join(HERE, src), tag)
    open(os.path.join(HERE, dst), "w", encoding="utf-8").write(
        "// Generated by make_speech.py from %s – do not edit by hand\nmodule.exports = %s;\n" % (src, json.dumps(d, ensure_ascii=False, indent=1)))
    print(dst, len(d), "slides")
