function practice(p) {
  const L = LECTURES[p.lecture - 1];
  const o = [];
  o.push(H2(`3.${p.num} ДАДЛАГА ${p.num}. ${p.title.toUpperCase()}`));
  o.push(table([2800, 6554], [
    ["Холбогдох лекц", `Лекц ${L.num}. ${L.title}`],
    ["Хугацаа", "4 цаг"],
    ["Байршил", p.room],
    ["Зохион байгуулах хэлбэр", p.form],
    ["Суралцахуйн үр дүн", p.clos.join(", ")],
    ["Бүтээгдэхүүн", p.product],
    ["Үнэлгээ", "5 оноо"],
  ], { size: 22 }));

  o.push(H3("Зорилго"));
  o.push(P(p.goal));
  o.push(H3("Зорилт"));
  p.objectives.forEach((t) => o.push(B(t)));

  o.push(H3("Бэлтгэл ажил"));
  o.push(table([4677, 4677], [
    ["Багш", "Сонсогч"],
    [{ v: p.teacherPrep.map((t) => "- " + t), valign: "top" }, { v: p.studentPrep.map((t) => "- " + t), valign: "top" }],
  ], { header: true }));

  o.push(H3("Хэрэглэгдэхүүн"));
  p.tools.forEach((t) => o.push(B(t)));

  o.push(H3("Дадлагын явц (цагийн хуваарь)"));
  o.push(table([1100, 3654, 2300, 2300], [
    ["Цаг", "Үйл ажиллагаа", "Багшийн үүрэг", "Сонсогчийн үүрэг"],
    ...p.hours.map((h) => [{ v: h.h, bold: true, align: CTR }, h.act.map((a) => "- " + a), h.t, h.s]),
  ], { header: true }));

  o.push(H3("Даалгаврын дэлгэрэнгүй"));
  p.tasks.forEach((t) => {
    o.push(new Paragraph({ keepNext: true, spacing: { before: 120, after: 60 }, children: [new TextRun({ text: t.h, bold: true })] }));
    t.steps.forEach((s, i) => o.push(step(i + 1, s)));
  });

  o.push(H3("Хүлээлгэн өгөх үр дүн"));
  p.deliverables.forEach((t) => o.push(B(t)));

  o.push(H3("Үнэлгээний шалгуур"));
  const total = p.rubric.reduce((a, r) => a + parseFloat(r[1]), 0);
  o.push(table([7854, 1500], [
    ["Шалгуур", "Оноо"],
    ...p.rubric.map((r) => [r[0], { v: r[1], align: CTR }]),
    [{ v: "Нийт", bold: true }, { v: String(total), bold: true, align: CTR }],
  ], { header: true }));

  if (p.safety) {
    o.push(H3("Аюулгүй ажиллагаа, ёс зүйн сануулга"));
    o.push(P([{ text: p.safety, italics: true }]));
  }
  o.push(H3("Дараагийн бие даалт"));
  o.push(P(p.homework));
  o.push(BR());
  return o;
}

