def fix_row(m):
    row = m.group(0)
    cells = re.findall(r'<w:tc>.*?</w:tc>', row, re.S)
    if len(cells) < 5:
        return row
    last = cells[-1]
    def dup(t):
        v = t.group(2)
        return t.group(1) + (f'{v} / {v}' if re.fullmatch(r'\d+', v) else v) + t.group(3)
    new_last = re.sub(r'(<w:t[^>]*>)([^<]*)(</w:t>)', dup, last)
    return row.replace(last, new_last)
