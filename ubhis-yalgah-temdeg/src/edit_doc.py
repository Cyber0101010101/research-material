def pid():
    while True:
        v = '%08X' % random.randint(0x10000000, 0x7FFFFFFF)
        if v not in used:
            used.add(v); return v
def fresh_ids(x):
    return re.sub(r'w14:paraId="[0-9A-F]{8}"', lambda m: f'w14:paraId="{pid()}"', x)

PARA = re.compile(r'<w:p[ >](?:(?!<w:p[ >]).)*?</w:p>', re.S)

def find_para(marker, start=0, exact=False):
    """Return (start, end, xml) of the single paragraph whose text contains (or equals) marker."""
    hits = []
    for m in PARA.finditer(d, start):
        t = ''.join(re.findall(r'<w:t[^>]*>([^<]*)</w:t>', m.group(0)))
        if (t == marker) if exact else (marker in t):
            hits.append(m)
    assert len(hits) == 1, (marker, len(hits))
    m = hits[0]
    return m.start(), m.end(), m.group(0)

def ppr(xml):
    m = re.search(r'<w:pPr>.*?</w:pPr>', xml, re.S)
    return m.group(0) if m else ''

def base_rpr(xml):
    """rPr of the first run, with bold removed."""
    m = re.search(r'<w:r>(?:<w:rPr>(.*?)</w:rPr>)?', xml, re.S)
    r = (m.group(1) or '') if m else ''
    return re.sub(r'<w:b/>|<w:bCs/>', '', r)

def runs(parts, rpr):
    out = ''
    for txt, bold in parts:
        rp = ('<w:b/><w:bCs/>' if bold else '') + rpr
        rp = f'<w:rPr>{rp}</w:rPr>' if rp else ''
        out += f'<w:r>{rp}<w:t xml:space="preserve">{escape(txt)}</w:t></w:r>'
    return out

def P(parts):
    """Parse '**bold**' markup into run parts."""
    out = []
    for i, seg in enumerate(re.split(r'\*\*', parts)):
        if seg:
            out.append((seg, i % 2 == 1))
    return out

def rebuild(xml, text, keep_bookmarks=True):
    head = re.match(r'<w:p[^>]*>', xml).group(0)
    bm_s = ''.join(re.findall(r'<w:bookmarkStart[^>]*/>', xml)) if keep_bookmarks else ''
    bm_e = ''.join(re.findall(r'<w:bookmarkEnd[^>]*/>', xml)) if keep_bookmarks else ''
    return f'{head}{ppr(xml)}{bm_s}{runs(P(text), base_rpr(xml))}{bm_e}</w:p>'

def set_para(marker, text, start=0, exact=False):
    global d
    s, e, x = find_para(marker, start, exact)
    d = d[:s] + rebuild(x, text) + d[e:]

def insert_after(marker, xml_list, exact=False):
    global d
    s, e, x = find_para(marker, 0, exact)
    d = d[:e] + ''.join(xml_list) + d[e:]

def remove_para(marker, exact=False):
    global d
    s, e, x = find_para(marker, 0, exact)
    d = d[:s] + d[e:]

def remove_row(marker, exact=False):
    global d
    s, e, x = find_para(marker, 0, exact)
    rs = d.rfind('<w:tr ', 0, s); re_ = d.index('</w:tr>', s) + 7
    d = d[:rs] + d[re_:]

def txt_replace(old, new, count=1):
    """Replace text inside whole <w:t> elements (keeps TOC hyperlinks/fields intact)."""
    global d
    pat = re.compile(r'(<w:t(?: [^>]*)?>)' + re.escape(old) + r'(</w:t>)')
    assert len(pat.findall(d)) == count, (old, len(pat.findall(d)))
    d = pat.sub(lambda m: m.group(1) + escape(new) + m.group(2), d)

