def resize_existing(rid, fname, width_emu):
    """Update extents of the drawing that embeds rid to the new image's aspect ratio."""
    global d
    w, h = Image.open(os.path.join(FIG, fname)).size
    cy = int(width_emu * h / w)
    for m in PARA.finditer(d):
        x = m.group(0)
        if f'r:embed="{rid}"' in x:
            y = re.sub(r'<wp:extent cx="\d+" cy="\d+"/>', f'<wp:extent cx="{width_emu}" cy="{cy}"/>', x)
            y = re.sub(r'<a:ext cx="\d+" cy="\d+"/>', f'<a:ext cx="{width_emu}" cy="{cy}"/>', y)
            d = d[:m.start()] + y + d[m.end():]
            return
    raise SystemExit('rid not found ' + rid)

