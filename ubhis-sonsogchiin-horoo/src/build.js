function cell(text, width, o = {}) {
  const paras = (Array.isArray(text) ? text : [text]).map(
    (t) =>
      new Paragraph({
        alignment: o.align || AlignmentType.LEFT,
        spacing: { after: 40, line: 264 },
        children: runs(t, { size: o.size || 19, bold: o.bold, color: o.color }),
      })
  );
  return new TableCell({
    width: { size: width, type: WidthType.DXA },
    borders,
    columnSpan: o.span,
    verticalAlign: o.valign || VerticalAlign.TOP,
    shading: o.fill ? { fill: o.fill, type: ShadingType.CLEAR, color: "auto" } : undefined,
    margins: { top: 70, bottom: 70, left: 100, right: 100 },
    children: paras,
  });
}

// headers: string[], rows: string[][], widths: number[] (нийлбэр = W)
function table(headers, rows, widths, o = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const head = new TableRow({
    tableHeader: true,
    children: headers.map((h, i) =>
      cell(h, widths[i], { bold: true, color: C.white, fill: C.navy, size: 19, valign: VerticalAlign.CENTER })
    ),
  });
  const body = rows.map(
    (r, ri) =>
      new TableRow({
        children: r.map((c, i) =>
          cell(c, widths[i], {
            fill: i === 0 && o.firstColFill ? o.firstColFill : ri % 2 === 1 ? "F7F8FA" : undefined,
            bold: i === 0 && o.firstColBold,
          })
        ),
      })
  );
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    rows: [head, ...body],
  });
}
