// Тодруулсан хайрцаг (нэг нүдтэй хүснэгт)
function box(title, lines, fill = C.blueLt, accent = C.steel) {
  const side = { style: BorderStyle.SINGLE, size: 24, color: accent };
  const none = { style: BorderStyle.NONE, size: 0, color: "FFFFFF" };
  return new Table({
    width: { size: W, type: WidthType.DXA },
    columnWidths: [W],
    rows: [
      new TableRow({
        children: [
          new TableCell({
            width: { size: W, type: WidthType.DXA },
            borders: { left: side, top: none, bottom: none, right: none },
            shading: { fill, type: ShadingType.CLEAR, color: "auto" },
            margins: { top: 120, bottom: 120, left: 200, right: 200 },
            children: [
              new Paragraph({
                spacing: { after: 80 },
                children: [new TextRun({ text: title, bold: true, color: accent, size: 21 })],
              }),
              ...lines.map(
                (l) =>
                  new Paragraph({
                    spacing: { after: 60, line: 276 },
                    numbering: l.startsWith("- ") ? { reference: "bullets", level: 0 } : undefined,
                    children: runs(l.replace(/^- /, ""), { size: 20 }),
                  })
              ),
            ],
          }),
        ],
      }),
    ],
  });
}

// Бүтцийн схемийн нэг түвшин: нүднүүд (тэнцүү өргөнтэй)
function orgLevel(items, fill, o = {}) {
  const n = items.length;
  const gap = o.gap ?? 120;
  const usable = (o.width || W) - gap * (n - 1);
  const cw = Math.floor(usable / n);
  const widths = [];
  const cells = [];
  const none = { style: BorderStyle.NONE, size: 0, color: "FFFFFF" };
  const bx = { style: BorderStyle.SINGLE, size: 8, color: o.border || C.navy };
  items.forEach((it, i) => {
    if (i > 0) {
      widths.push(gap);
      cells.push(
        new TableCell({
          width: { size: gap, type: WidthType.DXA },
          borders: { top: none, bottom: none, left: none, right: none },
          children: [new Paragraph({ children: [] })],
        })
      );
    }
    widths.push(cw);
    const lines = Array.isArray(it) ? it : [it];
    cells.push(
      new TableCell({
        width: { size: cw, type: WidthType.DXA },
        borders: { top: bx, bottom: bx, left: bx, right: bx },
        verticalAlign: VerticalAlign.CENTER,
        shading: { fill: (o.fills && o.fills[i]) || fill, type: ShadingType.CLEAR, color: "auto" },
        margins: { top: 80, bottom: 80, left: 80, right: 80 },
        children: lines.map(
          (l, li) =>
            new Paragraph({
              alignment: AlignmentType.CENTER,
              spacing: { after: 20, line: 252 },
              children: runs(l, {
                size: li === 0 ? (o.size || 18) : (o.size || 18) - 2,
                bold: li === 0,
                color: o.color || C.navy,
              }),
            })
        ),
      })
    );
  });
  const total = widths.reduce((a, b) => a + b, 0);
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    alignment: AlignmentType.CENTER,
    rows: [new TableRow({ children: cells })],
  });
}
